//! 実測のスキル回数表(60 秒あたり)。DPS はこれを使う(格子の外だけ式)。
//!
//! **キャラのパッシブ・自己バフはここには無い**(`crates/gamedata/src/character_skills.rs`)。
//! 中ディレイ減少の供給源は効き先の 1 つでしかなく、同じスキルがステや攻撃ダメージにも
//! 効くので、スキルはキャラスキルのカタログにまとめている。共通の供給源
//! (フルスロットル / カフスのランダムオプション / シエナのオーラ)はそれぞれ
//! `UltimateSkills` / `RandomOptionTotals` / `SienaAura` から入る。

use domain::SkillUsesTable;

use crate::Source;

/// 実測のスキル回数表(60 秒あたり)。出典: ユーザー提供の計測表
/// 「260702 테섭 허수아비 기준」(テスト鯖の訓練用かかし基準。2026-08-25 提供)。
///
/// wiki `#ActualDelay` 自身が「中ディレイ減少値を特定の値まで上げると、スキルの発動頻度が
/// 急激に変化する場合がある(丸め処理や通信頻度、入力間隔の都合)」と書いているとおり、
/// 実際の発動回数は `60 / 中ディレイ` にならない(詠唱・入力の overhead で 3〜14% 少ない)。
///
/// 元表の行は「フルスロットル −45% + カフスのランダムオプション −3% = **48%** に**積み増す** %」で、
/// `그외 캐릭터 16%`(シエナのオーラ 2% × 8 部位)/ `밀라・비호・이솔렛 21%`(+ パッシブ 5%)/
/// `보리스 26%`(+ 剣の司祭 5% + 一閃 5%)。ボリスの `26% (실적용22%)` は
/// 48 + 26 = 74% が**上限 70% で頭打ち**になった結果で、実装の
/// `ACTUAL_DELAY_REDUCTION_MAX` と一致する。ここでは**総減少 %** に直して持つ。
pub const SKILL_USES_SOURCE: Source = Source {
    page: "ユーザー提供の計測表「260702 테섭 허수아비 기준」",
    retrieved_on: "2026-08-25",
    note: "60 秒あたりのスキル回数。行は総中ディレイ減少 %(元表は フルスロットル45 + カフスRO3 = 48%            への積み増し表記)、列は基本中ディレイ。格子の外は式で出す",
};

/// 総中ディレイ減少 %(元表の 0/2/…/16/21/26% に 48% を足したもの。26% は上限 70% で頭打ち)。
const USES_REDUCTIONS: [f64; 11] = [48.0, 50.0, 52.0, 54.0, 56.0, 58.0, 60.0, 62.0, 64.0, 69.0, 70.0];
/// 基本中ディレイ(秒)。元表の列。
const USES_BASE_DELAYS: [f64; 5] = [0.8, 1.0, 1.2, 1.4, 1.6];
/// `[総減少 %][基本中ディレイ]` = 60 秒あたりのスキル回数。
#[rustfmt::skip]
const USES: [[f64; 5]; 11] = [
    [135.0, 110.0,  93.0,  79.0,  69.0], // 48%(積み増し  0%)
    [137.0, 114.0,  95.0,  82.0,  71.0], // 50%(積み増し  2%)
    [141.0, 116.0,  98.0,  87.0,  77.0], // 52%(積み増し  4%)
    [148.0, 124.0, 101.0,  89.0,  80.0], // 54%(積み増し  6%)
    [150.0, 129.0, 106.0,  92.0,  81.0], // 56%(積み増し  8%)
    [160.0, 132.0, 112.0,  96.0,  86.0], // 58%(積み増し 10%)
    [167.0, 138.0, 119.0, 104.0,  89.0], // 60%(積み増し 12%)
    [172.0, 145.0, 122.0, 106.0,  93.0], // 62%(積み増し 14%)
    [176.0, 154.0, 127.0, 110.0, 100.0], // 64%(積み増し 16% = シエナのオーラ 2%×8 部位)
    [181.0, 172.0, 144.0, 127.0, 115.0], // 69%(積み増し 21% = + パッシブ 5%。ミラ / イソレット等)
    [180.0, 178.0, 153.0, 130.0, 117.0], // 70%(積み増し 26% → 上限で実適用 22%。ボリス)
];

/// 実測のスキル回数表。DPS はこれを使う(格子の外だけ式)。
pub fn skill_uses_table() -> SkillUsesTable {
    SkillUsesTable {
        reduction_percents: USES_REDUCTIONS.to_vec(),
        base_delays: USES_BASE_DELAYS.to_vec(),
        uses: USES.iter().map(|row| row.to_vec()).collect(),
    }
}

#[cfg(test)]
mod uses_tests {
    use super::*;

    #[test]
    fn 表は11行5列で回数は減少値が大きいほど増える() {
        let t = skill_uses_table();
        assert_eq!(t.reduction_percents.len(), 11);
        assert_eq!(t.base_delays.len(), 5);
        assert!(t.uses.iter().all(|row| row.len() == 5));
        // 基本中ディレイが長いほど回数は少ない
        for row in &t.uses {
            assert!(row.windows(2).all(|w| w[0] > w[1]), "{row:?}");
        }
        // 上限 70% の行が最後(実装の ACTUAL_DELAY_REDUCTION_MAX と一致)
        assert_eq!(*t.reduction_percents.last().unwrap(), domain::ACTUAL_DELAY_REDUCTION_MAX * 100.0);
    }

    #[test]
    fn 格子の中は実測で外はnone() {
        let t = skill_uses_table();
        // 総減少 48% ・ 基本 0.8s → 実測 135 回/分
        assert_eq!(t.uses_per_minute(0.8, 0.48), Some(135.0));
        // 総減少 70% ・ 基本 1.6s → 117 回/分
        assert_eq!(t.uses_per_minute(1.6, 0.70), Some(117.0));
        // 格子の外(フルスロットル未習得・チャネリングの長い動作)は None
        assert_eq!(t.uses_per_minute(0.8, 0.10), None);
        assert_eq!(t.uses_per_minute(10.0, 0.48), None);
    }

    #[test]
    fn 実測は式より少ない() {
        let t = skill_uses_table();
        // 式なら 60 / (0.8 × 0.52) = 144.2 回/分。実測は 135 回/分(overhead 分)
        let measured = t.uses_per_minute(0.8, 0.48).unwrap();
        assert!(measured < 60.0 / (0.8 * 0.52));
    }
}
